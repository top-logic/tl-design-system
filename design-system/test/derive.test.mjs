// Gate für den Kern von derive: die erzeugte Datei trägt nur Abweichungen, jede gerechnete Rolle
// hält ihr Paar, die Kategorien trennen sich, das Grau liegt auf unseren Helligkeiten, und ein
// gelieferter Wert unter AA reist als Befund mit.
