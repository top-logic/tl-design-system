const MODES = ['light', 'dark'];

test('1 die Datei trägt genau die abweichenden Rollen, beide Blöcke dieselben Farbrollen, :root unberührt', () => {
  const { rollen, css } = ergebnis;
  assert.deepEqual(Object.keys(rollen.light).sort(), Object.keys(rollen.dark).sort());
  assert.ok('surface-brand' in rollen.light && 'text-on-brand' in rollen.light && 'radius-sm' in rollen.measure);
  assert.ok(!('surface-base' in rollen.light) || rollen.light['surface-base'] !== R0.color.light['surface-base']);
  assert.ok(!('size-control' in rollen.measure));
  assert.ok(css.startsWith('/* Generated by TopLogic/tl-design-system'));
  assert.ok(css.includes('[data-tl-theme="probe"] {') && css.includes('[data-tl-theme="probe"][data-tl-mode="dark"] {'));
  assert.ok(!css.includes(':root') && !css.includes('var('));
  assert.equal(readFileSync(new URL('../dist/tokens.css', import.meta.url), 'utf8').includes('probe'), false);
});

test('2 jede gerechnete Rolle besteht die Paarliste in beiden Modi', () => {
  const Rk = ergebnis.ergebnis;
  for (const mode of MODES) for (const { fg, bg, soll } of kontrastPaare(T)) {
    const ist = ratio(werte(Rk, mode, fg), werte(Rk, mode, bg));
    // Entschuldigt ist ein Paar nur, wenn sein Befund aus einem GELIEFERTEN Wert stammt —
    // sonst entschuldigte sich die Liste der Befunde selbst.
    const geliefert = ergebnis.befunde.some((b) => b.mode === mode && b.fg === fg && b.bg === bg && b.geliefert);
    assert.ok(ist >= soll || geliefert, `${mode}: ${fg} auf ${bg} = ${ist.toFixed(2)}`);
  }
});

test('3 die Kategorien halten 20° zur Marke, zu jeder Bedeutung und zueinander', () => {
  for (const mode of MODES) {
    const C = ergebnis.ergebnis.color[mode];
    const tints = Array.from({ length: 8 }, (_, i) => C[`category-${i + 1}-subtle`]);
    const fest = ['surface-brand-subtle', 'status-error-subtle', 'status-warning-subtle', 'status-success-subtle', 'status-info-subtle'].map((n) => C[n]);
    for (let i = 0; i < 8; i++) {
      for (let j = i + 1; j < 8; j++) assert.ok(farbtonAbstand(tints[i], tints[j]) >= 20, `${mode} ${i + 1}↔${j + 1}`);
      for (const f of fest) assert.ok(farbtonAbstand(tints[i], f) >= 20, `${mode} ${i + 1}↔fest`);
    }
  }
});

test('5 warm liegt auf den Helligkeiten von TopLogic-Grau; neutral trägt keine Chroma', () => {
  assert.ok(Math.abs(hexZuOklch(ergebnis.ergebnis.color.light['text-primary']).L - hexZuOklch(R0.color.light['text-primary']).L) < 0.01);
  const neutral = derive(P, T, { ...probe, color: { ...probe.color, gray: 'neutral' } });
  assert.ok(hexZuOklch(neutral.ergebnis.color.light['text-secondary']).C < 0.002);
});

test('die Schleier folgen dem Kundengrau und behalten ihre Deckkraft; ein gelieferter Schleier bleibt', () => {
  for (const mode of MODES) for (const s of ['surface-state-hover', 'surface-state-active']) {
    const vorher = rgba(R0.effect[mode][s]);
    const nachher = rgba(ergebnis.ergebnis.effect[mode][s]);
    assert.equal(nachher.a, vorher.a, `${mode}: ${s} Deckkraft`);
    // Die Farbe ist die Stufe des Textes, aus der Rampe des Kunden.
    const text = ergebnis.ergebnis.color[mode]['text-primary'];
    assert.equal(ueberlagert(`rgba(${nachher.r}, ${nachher.g}, ${nachher.b}, 1)`, '#000000'), text, `${mode}: ${s} folgt nicht dem Grau`);
    assert.ok(ergebnis.css.includes(`--tl-${s}: ${ergebnis.ergebnis.effect[mode][s]};`), `${mode}: ${s} fehlt in der Datei`);
  }
  const eigen = derive(P, T, { theme: 'eigen', color: { gray: 'warm' }, effect: { 'veil-1': 'rgba(0, 0, 0, 0.1)' } });
  assert.equal(eigen.ergebnis.effect.light['surface-state-hover'], 'rgba(0, 0, 0, 0.1)');
  // Ohne Grau bleibt der Schleier der von TopLogic und erscheint nicht in der Datei.
  assert.doesNotMatch(derive(P, T, { theme: 'marke', color: { brand: '#7A1FA2' } }).css, /surface-state-/);
});

test('eine Saat mittlerer Helligkeit macht ihre Beschriftung zum Befund, nicht zum Abbruch', () => {
  for (const brand of ['#808080', '#1A7F37']) {
    const r = derive(P, T, { theme: 'mittel', color: { brand } });
    const b = r.befunde.filter((x) => x.fg.startsWith('text-on-brand'));
    assert.ok(b.length >= 1, `${brand}: kein Befund auf einer Markenfläche`);
    assert.ok(b.every((x) => x.geliefert), `${brand}: die Saat ist geliefert, der Befund auch`);
    assert.ok(r.css.includes(`--tl-surface-brand: ${brand};`), `${brand}: die Fläche bleibt die Marke`);
  }
});

