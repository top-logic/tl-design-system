// Erzeugt dist/ aus src/. Was hier nicht herauskommt, gibt es im Design System nicht.
import { resolve, primitives } from './resolve.mjs';
import { dtcg } from './dtcg.mjs';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Alle CSS-Dateien unter src/components/, rekursiv, sortiert nach Pfad. Name relativ mit '/'. */
export function componentSources(dirUrl) {
  const root = fileURLToPath(dirUrl);
  const files = [];
  (function walk(dir) {
    for (const entry of readdirSync(dir).sort()) {
      const p = join(dir, entry);
      if (statSync(p).isDirectory()) walk(p);
      else if (entry.endsWith('.css')) files.push(p);
    }
  })(root);
  return files.sort().map((p) => ({ name: relative(root, p).split(sep).join('/'), css: readFileSync(p, 'utf8') }));
}

function componentsCss(components) {
  return `${HERKUNFT}/* Components, one section per file under src/components/. */\n\n`
    + components.map((c) => `/* --- ${c.name} --- */\n${c.css.trimEnd()}\n`).join('\n');
}

const REF = /^\{([a-z0-9-]+)\}$/;
const line = (n, v) => `  --tl-${n}: ${v};`;
const asVar = (v) => { const m = REF.exec(String(v)); return m ? `var(--tl-${m[1]})` : v; };
const block = (o) => Object.entries(o).filter(([k]) => !k.startsWith('_')).map(([n, v]) => line(n, asVar(v))).join('\n');
// Jede erzeugte Datei nennt ihre Herkunft: Sie wird in andere Repos kopiert (tl-engine-7 lädt sie als
// ClientResource), und wer sie dort findet, soll wissen, wo die Quelle liegt und dass er hier nichts ändert.
const HERKUNFT = `/* Generated by TopLogic/tl-design-system (design-system/src, tools/generate.mjs).
   Do not edit — edit the source and regenerate. Rules and reasoning: repo wiki and docs/skalen.md.
   https://git.top-logic.com/TopLogic/tl-design-system/wiki */\n`;
const HEAD = `${HERKUNFT}\n`;

function primitivesCss(P) {
  return `${HEAD}/* Schicht 1: Primitive. Reine Werte ohne Bedeutung — die Stelle, an der ein
   Kundenprojekt eingreift. Wer hier einen Wert überschreibt, ändert jede Rolle mit. */
:root {
${block(primitives(P))}
}
`;
}

function tokensCss(P, T, R) {
  const derived = (mode) => Object.entries(R.derived[mode]).map(([n, v]) => line(n, v)).join('\n');
  return `${HEAD}/* Schicht 2: Rollen. Jede verweist auf eine Primitive, keine trägt einen Wert.
   Ausnahme: Beschriftungen auf Flächen (--tl-text-on-*, --tl-icon-on-*) sind gerechnet. */
:root,
[data-tl-mode="light"] {
  color-scheme: light;
${block(T.measure)}
${block(T.layer)}

${block(T.color.light)}
${derived('light')}

${block(T.effect.light)}

${block(T.density.normal)}
}

[data-tl-mode="dark"] {
  color-scheme: dark;
${block(T.color.dark)}
${derived('dark')}

${block(T.effect.dark)}
}

[data-tl-density="compact"] {
${block(T.density.compact)}
}
`;
}

function baseCss(T) {
  const type = Object.entries(T.type).filter(([k]) => !k.startsWith('_')).map(([n, k]) => `.tl-type-${n} {
  font-family: var(--tl-font-family-${k.family});
  font-size: var(--tl-font-size-${k.size});
  font-weight: ${k.weight};
  line-height: ${k.lineHeight};
  letter-spacing: ${k.tracking};
}`).join('\n\n');
  const print = Object.entries(T.print).map(([n, k]) => `  .tl-print-${n} {
    font-size: ${k.size};
    font-weight: ${k.weight};
    line-height: ${k.lineHeight};
  }`).join('\n');
  return `${HEAD}/* Grundklassen. Jede liest nur Variablen. */
html {
  -webkit-text-size-adjust: 100%;
}

body {
  margin: 0;
  background: var(--tl-surface-base);
  color: var(--tl-text-primary);
  font-family: var(--tl-font-family-sans);
}

*, *::before, *::after {
  box-sizing: border-box;
}

/* Typografie: eine Größe ist keine Klasse. Die Klasse legt alles fest. */
${type}

/* Zahlen in Spalten fluchten nur mit tabellarischen Ziffern. Pflicht, nicht Option. */
.tl-nums {
  font-feature-settings: "tnum" 1, "zero" 1;
  font-variant-numeric: tabular-nums slashed-zero;
}

/* Sichtbar nur für Screenreader: das Clipping verbirgt das Element, die absolute Lage nimmt es aus
   dem Fluss, die Box von size-hidden hält einen langen Text davon ab, einen Rollbalken zu erzeugen —
   1 px statt 0, damit Screenreader das Element nicht als leer überspringen. inset(50%) ist ein
   Anteil, kein Maß, und darum kein Versehen. Ersetzt tlVisuallyHidden des Altbestands. */
.tl-visually-hidden {
  position: absolute;
  width: var(--tl-size-hidden);
  height: var(--tl-size-hidden);
  overflow: hidden;
  clip-path: inset(50%);
  white-space: nowrap;
  margin: 0;
  padding: 0;
  border: 0;
}

/* Der Ring gehört der Tastatur. Ein Mechanismus, außen, nur beim Tastaturfokus. */
:where(a, button, input, select, textarea, summary, [tabindex], [contenteditable]):focus-visible {
  outline: var(--tl-focus-width) solid var(--tl-focus-ring);
  outline-offset: var(--tl-focus-offset);
}

/* Icons: drei Stufen nach Rolle plus Glyph im Control — siehe skalen.md „Icons“.
   line-height 1, sonst erbt der Glyph die Zeilenhöhe des Fließtexts; das 1em-Quadrat hält
   Menü- und Baumspalten in Flucht. Die Fläche einer Icon-Schaltfläche ist Sache des Controls. */
.tl-icon-glyph, .tl-icon-sm, .tl-icon-md, .tl-icon-lg {
  line-height: 1;
  width: 1em;
  height: 1em;
  display: inline-block;
  text-align: center;
  flex-shrink: 0;
}
.tl-icon-glyph { font-size: var(--tl-size-icon-glyph); }
.tl-icon-sm { font-size: var(--tl-size-icon-sm); }
.tl-icon-md { font-size: var(--tl-size-icon-md); }
.tl-icon-lg { font-size: var(--tl-size-icon-lg); }

/* Wer Bewegung abbestellt hat, hat sie abbestellt. 0.01ms statt 0, sonst feuert transitionend nie. */
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}

/* Druck: rem hat im Druck keine Wurzel. Eigene Leiter in pt. */
@media print {
${print}
  .tl-print-title, .tl-print-heading, .tl-print-body, .tl-print-caption {
    font-variant-numeric: tabular-nums;
  }
}
`;
}

export function generate(P, T, components = []) {
  const R = resolve(P, T);
  return {
    'primitives.css': primitivesCss(P),
    'tokens.css': tokensCss(P, T, R),
    'base.css': baseCss(T),
    'components.css': componentsCss(components),
  };
}

if (typeof process !== 'undefined' && import.meta.url === `file://${process.argv[1]}`) {
  const { writeFileSync, mkdirSync } = await import('node:fs');
  const P = JSON.parse(readFileSync(new URL('../src/primitives.json', import.meta.url)));
  const T = JSON.parse(readFileSync(new URL('../src/tokens.json', import.meta.url)));
  const dist = new URL('../dist/', import.meta.url);
  mkdirSync(dist, { recursive: true });
  for (const [name, text] of Object.entries(generate(P, T, componentSources(new URL('../src/components/', import.meta.url))))) {
    writeFileSync(new URL(name, dist), text);
    console.log(`geschrieben: dist/${name}`);
  }
  writeFileSync(new URL('tokens.dtcg.json', dist), JSON.stringify(dtcg(P, T), null, 2) + '\n');
  console.log('geschrieben: dist/tokens.dtcg.json');
}
