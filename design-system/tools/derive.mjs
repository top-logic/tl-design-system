// tl-ds derive: ein Kundentheme aus einer Primitivdatei. Rechnet, was fehlt; lässt, was geliefert
// ist; schreibt nur Rollen, die von TopLogic abweichen; meldet, was ein Paar verfehlt.
// Spec: docs/superpowers/specs/2026-09-25-derive-design.md
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolve, primitives } from './resolve.mjs';
import { grauRampe, kategorienVerteilen, kategorieRollen, markenRollen, beschriftungAbleiten, hexZuOklch, aufKontrast, farbtonAbstand }
  from './lib/color.mjs';
import { kontrastPaare, werte } from './lib/pairs.mjs';
import { leseThemeEingabe, ThemeEingabeFehler } from './lib/theme-input.mjs';
import { ratio, rgba, color } from './lib/contrast.mjs';

const REF = /^\{([a-z0-9-]+)\}$/;
const MODES = ['light', 'dark'];
const KATEGORIEN = Array.from({ length: 8 }, (_, i) => i + 1);
/** Die Familie der Schleier: eine Graustufe mit Deckkraft, Wert der Zustandsschichten surface-state-*. */
const SCHLEIER = /^veil-\d+$/;
/**
 * Die drei Flächen, deren Helligkeit unmittelbar aus der Saat des Kunden kommt. Ihre
 * Beschriftungen (text-on-brand, -hover, -active, icon-on-brand) wählen nach der
 * Zwei-Kandidaten-Regel den besseren von Weiß und Fast-Schwarz — nicht den ausreichenden. Eine
 * Saat mittlerer Helligkeit lässt beide Kandidaten unter der Schwelle: das ist keine falsche
 * Rechnung, sondern die Folge einer GELIEFERTEN Farbe, also ein Befund, kein Abbruch. Die Fläche
 * selbst bleibt unangetastet — sie ist die Marke des Kunden.
 */
const MARKEN_FLAECHEN = ['surface-brand', 'surface-brand-hover', 'surface-brand-active'];
/** Ab diesem Farbtonabstand lesen sich zwei getönte Flächen als verschieden (docs/skalen.md). */
const KATEGORIE_ABSTAND_MIN = 20;
const grad = (hex) => ((hexZuOklch(hex).H * 180) / Math.PI + 360) % 360;

const HERKUNFT = (theme, quelle, anzahl) => `/* Generated by TopLogic/tl-design-system, tools/derive.mjs, from ${quelle}.
   Do not edit — edit the JSON and regenerate. Loaded after tokens.css; applies under data-tl-theme="${theme}".
   Findings: ${anzahl} ${anzahl === 1 ? 'pair' : 'pairs'} below its threshold${anzahl ? ' (see report at the end of this file)' : ''}. */\n`;

/** Die beiden Primitiven, aus denen jede Beschriftung gewählt wird. */
const KANDIDATEN_PRIMITIVE = (T) => [T.derived.candidates.dark, T.derived.candidates.light]
  .map((v) => REF.exec(String(v))?.[1]).filter(Boolean);

/** Primitive, die eine Rolle in einem Modus liest — für die Herkunft (geliefert oder gerechnet). */
function primitiveVon(T, mode, rolle) {
  const m = REF.exec(String(T.color[mode][rolle] ?? T.measure[rolle] ?? ''));
  return m ? m[1] : null;
}

export function derive(P, T, json, quelle = 'input') {
  const eingabe = leseThemeEingabe(json, P, T);
  const { theme, geliefert, saat } = eingabe;
  const hinweise = [];

  // 1 Gelieferte Stufen und die Graurampe liegen über den Primitiven.
  const Pk = structuredClone(P);
  if (saat.gray) {
    const grau = Object.fromEntries(Object.entries(P.color).filter(([n]) => n.startsWith('gray-')));
    Object.assign(Pk.color, grauRampe(saat.gray, grau));
  }
  // Jede gelieferte Stufe liegt in genau der Familie, zu der ihr Name gehört. Object.hasOwn statt
  // `in`, damit kein Name aus der Prototypkette (`constructor`, `toString`) eine Familie trifft.
  for (const [n, v] of Object.entries(geliefert)) {
    for (const f of Object.keys(Pk)) {
      if (f.startsWith('_') || !Pk[f] || typeof Pk[f] !== 'object') continue;
      if (Object.hasOwn(Pk[f], n)) Pk[f][n] = v;
    }
  }

  // 1b Die Schleier (durchscheinende Zustandsschichten, docs/skalen.md „Höfe sind durchscheinend“) sind eine
  // Graustufe mit Deckkraft. Rührt der Kunde das Grau an, folgt der Schleier seiner Stufe und behält seine
  // Deckkraft; einen gelieferten Schleier lässt derive stehen.
  for (const [n, v] of Object.entries(P.effect ?? {})) {
    if (!SCHLEIER.test(n) || Object.hasOwn(geliefert, n)) continue;
    const s = rgba(v);
    const stufe = Object.entries(P.color).find(([g, hex]) => g.startsWith('gray-')
      && hex === `#${[s.r, s.g, s.b].map((k) => k.toString(16).padStart(2, '0')).join('').toUpperCase()}`)?.[0];
    if (!stufe) throw new Error(`${n}: ${v} ist keine Graustufe mit Deckkraft`);
    if (Pk.color[stufe] === P.color[stufe]) continue;
    const k = color(Pk.color[stufe]);
    Pk.effect[n] = `rgba(${k.r}, ${k.g}, ${k.b}, ${s.a})`;
  }

  // 2 Auflösen: geliefertes zieht durch alle Rollen, Beschriftungen folgen den Flächen.
  const R0 = resolve(P, T);
  const Rk = resolve(Pk, T);
  const gruende = Object.fromEntries(MODES.map((m) => [m, [Rk.color[m]['surface-base'], Rk.color[m]['surface-layer']]]));

  // 3 Gerechnete Rollen überlagern, wo keine gelieferte Primitive dahintersteht.
  //
  // setze() meldet zurück, ob es geschrieben hat. Nur dann darf ein Hinweis der Rechnung übernommen
  // werden: sonst stünde in der Datei „text-link nachgeführt“ neben einem Befund, der beweist, dass
  // genau das nicht geschehen ist. Ein Hinweis, der eine Korrektur behauptet, die der Kunde
  // überschrieben hat, ist schlimmer als kein Hinweis.
  const geschrieben = new Set();
  const setze = (mode, rolle, hex) => {
    const prim = primitiveVon(T, mode, rolle);
    if (prim && Object.hasOwn(geliefert, prim)) {
      // Eine gelieferte Stufe bleibt gelieferte Stufe — aber lautlos wird sie nicht: eine
      // Kategorie, die an einer Markenstufe hängt (category-5-subtle ist {blue-4}), kippt sonst
      // unbemerkt auf den Markenton.
      if (rolle.startsWith('category-')) {
        hinweise.push(`${mode}: ${rolle} bleibt bei der gelieferten Stufe ${prim} und folgt damit nicht der Verteilung`);
      }
      return false;
    }
    Rk.color[mode][rolle] = hex;
    geschrieben.add(`${mode}:${rolle}`);
    return true;
  };
  if (saat.brand) {
    const m = markenRollen(saat.brand, gruende);
    for (const mode of MODES) for (const [rolle, hex] of Object.entries(m[mode])) setze(mode, rolle, hex);
    // Ein Hinweis nennt den Modus und die Rolle, um die es geht. Genannt ist jeweils der längste
    // passende Name (surface-brand-hover, nicht surface-brand); ein Hinweis ohne Rollennamen — die
    // unbunte Saat — gilt der Saat selbst und bleibt immer.
    const namen = Object.keys(m.light);
    hinweise.push(...m.hinweise.filter((h) => {
      const modus = /^(light|dark): /.exec(h);
      const genannt = namen.filter((r) => h.includes(r))
        .filter((r, _, alle) => !alle.some((a) => a !== r && a.startsWith(r)));
      if (genannt.length === 0) return true;
      return genannt.some((r) => geschrieben.has(modus ? `${modus[1]}:${r}` : `light:${r}`));
    }));
  }
  const markenTon = grad(Rk.color.light['surface-brand']);
  const bedeutungen = ['error', 'warning', 'success', 'info'].map((s) => grad(Rk.color.light[`status-${s}-surface`]));
  if (saat.brand) for (const b of bedeutungen) {
    const d = Math.abs(((markenTon - b) % 360 + 540) % 360 - 180);
    if (d < 20) hinweise.push(`die Marke liegt ${d.toFixed(0)}° neben einer Bedeutung; Stufe B entscheidet, ob die Bedeutung einen anderen Ton bekommt`);
  }
  // Die Kategorien werden nur angefasst, wenn eine Farbe sie bewegt: die Marke blockiert einen
  // Ton auf dem Kreis, das Kundengrau verschiebt die Gründe der Linien, eigene Kategorien setzen
  // Töne fest. Rührt der Kunde keine Farbe an, bleiben die acht Kategorien die von TopLogic —
  // sonst schriebe eine Datei, die nur einen Radius ändert, sechzehn Farbrollen um.
  // Ein geliefertes Grau zählt als Farbe, ob es als Temperatur oder als Stufenobjekt kommt — die
  // Spec kennt da keinen Unterschied, und die Linien der Kategorien hängen an den Gründen.
  const grauGeliefert = Object.keys(geliefert).some((n) => n.startsWith('gray-'));
  if (saat.brand || saat.gray || saat.category || grauGeliefert) {
    const eigene = saat.category ?? {};
    const fehlende = KATEGORIEN.filter((k) => !(`category-${k}` in eigene));
    const { toene, abstand } = kategorienVerteilen([markenTon, ...bedeutungen, ...Object.values(eigene).map(grad)], fehlende.length);
    const toneJeKategorie = Object.fromEntries([...KATEGORIEN.map((k) => [k, eigene[`category-${k}`] ? grad(eigene[`category-${k}`]) : null])]);
    fehlende.forEach((k, i) => { toneJeKategorie[k] = toene[i]; });
    let eineGeschrieben = false;
    for (const k of KATEGORIEN) {
      const r = kategorieRollen(toneJeKategorie[k], gruende);
      for (const mode of MODES) {
        eineGeschrieben = setze(mode, `category-${k}-subtle`, r[mode].subtle) || eineGeschrieben;
        eineGeschrieben = setze(mode, `category-${k}-border`, r[mode].border) || eineGeschrieben;
      }
    }
    // Der gesenkte Abstand ist nur dann eine Aussage über die Datei, wenn die Verteilung auch
    // irgendwo angekommen ist.
    if (abstand < 20 && eineGeschrieben) hinweise.push(`die Kategorien halten nur ${abstand}° zueinander; der Kreis war mit dieser Marke voller als bei TopLogic`);
  }

  // 3b Die Trennung im Farbton am fertigen Ergebnis prüfen, nicht an der Verteilung.
  //
  // Die Verteilung rechnet mit Tönen; was am Ende in der Datei steht, kann ein anderer Ton sein —
  // eine gelieferte Stufe unter einer Kategorie (category-5-subtle ist {blue-4}) zieht sie auf den
  // Markenton, ohne dass die Verteilung davon weiß. Geprüft wird deshalb der Befund, nicht die
  // Absicht: jede Kategorie gegen jede andere und gegen jede feste Bedeutung.
  for (const mode of MODES) {
    const kategorien = KATEGORIEN.map((k) => [`category-${k}-subtle`, Rk.color[mode][`category-${k}-subtle`]]);
    const feste = ['surface-brand-subtle', ...['error', 'warning', 'success', 'info'].map((s) => `status-${s}-subtle`)]
      .map((n) => [n, Rk.color[mode][n]]);
    for (let i = 0; i < kategorien.length; i++) {
      for (const [n, hex] of [...kategorien.slice(i + 1), ...feste]) {
        const d = farbtonAbstand(kategorien[i][1], hex);
        if (d < KATEGORIE_ABSTAND_MIN) hinweise.push(`${mode}: ${kategorien[i][0]} und ${n} liegen nur ${d.toFixed(0)}° auseinander und lesen sich als dieselbe Tönung`);
      }
    }
  }

  // 4 Beschriftungen für jede Fläche neu, mit den Kandidaten des Kundengraus.
  const prim = primitives(Pk);
  const kandidaten = { dunklerKandidat: prim[REF.exec(T.derived.candidates.dark)[1]], hellerKandidat: prim[REF.exec(T.derived.candidates.light)[1]] };
  for (const mode of MODES) for (const [name, { surface }] of Object.entries(T.derived[mode]))
    Rk.derived[mode][name] = beschriftungAbleiten(Rk.color[mode][surface], kandidaten).hex;

  // 5 Nachführen: derive steht für jeden Wert ein, den es nicht geliefert bekommen hat.
  //
  // Die Graurampe des Kunden ändert die Flächen, nicht aber die Bedeutungsfarben, die TopLogic
  // unverändert lässt. Unsere Palette hat an mehreren Paaren nur Rundungsluft (status-warning-text
  // auf surface-base steht bei 4,50001), also rutscht ein solches Paar bei jeder Temperatur unter
  // seine Schwelle — nicht, weil die Rechnung falsch ist, sondern weil der Grund ein anderer ist.
  // Ein solcher Wert ist nicht geliefert; also führt derive ihn nach, mit derselben Mechanik, die
  // markenRollen und kategorieRollen schon benutzen. Damit gilt die Regel der Spec ohne Ausnahme:
  // ein Befund entsteht nur aus einem GELIEFERTEN Wert.
  //
  // Ein Durchgang genügt, weil die Vordergründe der Paarliste nie Hintergründe sind: eine Rolle,
  // die hier bewegt wird, steht in keinem anderen Paar als Grund und kann deshalb kein schon
  // geprüftes Paar wieder aufreißen. pairs.test.mjs hält diese Invariante fest.
  const paare = kontrastPaare(T);
  for (const mode of MODES) {
    const jeRolle = new Map();
    for (const { fg, bg, soll } of paare) {
      if (!(fg in Rk.color[mode])) continue; // Beschriftungen folgen ihrer Fläche, nicht dem Kontrast
      const p = primitiveVon(T, mode, fg);
      if (p && Object.hasOwn(geliefert, p)) continue; // geliefert: bleibt stehen und wird zum Befund
      if (!jeRolle.has(fg)) jeRolle.set(fg, []);
      jeRolle.get(fg).push({ bg, soll });
    }
    for (const [rolle, liste] of jeRolle) {
      const vorher = Rk.color[mode][rolle];
      let hex = vorher;
      for (const soll of [...new Set(liste.map((x) => x.soll))].sort((a, b) => a - b)) {
        const gegen = liste.filter((x) => x.soll === soll).map((x) => werte(Rk, mode, x.bg));
        try { hex = aufKontrast(hex, gegen, soll, mode === 'light' ? 'dunkler' : 'heller').hex; } catch { /* der Befund meldet es */ }
      }
      if (hex === vorher) continue;
      Rk.color[mode][rolle] = hex;
      hinweise.push(`${mode}: ${rolle} in der Helligkeit nachgeführt, damit es auf seinem Grund hält (${vorher} → ${hex})`);
    }
  }

  // 6 Differenz: beide Blöcke tragen dieselben Farbrollen.
  const farbRollen = [...Object.keys(T.color.light), ...Object.keys(T.derived.light)].filter((k) => !k.startsWith('_'));
  const effektRollen = Object.keys(T.effect.light).filter((k) => !k.startsWith('_'));
  const abweichend = (r) => MODES.some((m) => werte(Rk, m, r) !== werte(R0, m, r));
  const U = farbRollen.filter(abweichend);
  const E = effektRollen.filter((r) => MODES.some((m) => Rk.effect[m][r] !== R0.effect[m][r]));
  const rollen = { light: {}, dark: {}, measure: {} };
  for (const mode of MODES) {
    for (const r of U) rollen[mode][r] = werte(Rk, mode, r);
    for (const r of E) rollen[mode][r] = Rk.effect[mode][r];
  }
  for (const r of Object.keys(T.measure).filter((k) => !k.startsWith('_'))) if (Rk.measure[r] !== R0.measure[r]) rollen.measure[r] = Rk.measure[r];

  // 7 Befunde: nur gelieferte Werte dürfen ein Paar verfehlen.
  const befunde = [];
  for (const mode of MODES) for (const { fg, bg, soll } of kontrastPaare(T)) {
    const ist = ratio(werte(Rk, mode, fg), werte(Rk, mode, bg));
    if (ist >= soll) continue;
    const pf = primitiveVon(T, mode, fg), pb = primitiveVon(T, mode, bg);
    const surfaceVon = T.derived[mode][fg]?.surface;
    // Eine Beschriftung hat drei gelieferte Quellen: ihre Fläche, die Saat hinter der Fläche und
    // die beiden Kandidaten, aus denen beschriftungAbleiten wählt. Liefert der Kunde gray-0, ist
    // der helle Kandidat seiner — dann ist auch das verfehlte Paar seines.
    const gelieferteBeschriftung = surfaceVon
      && (Object.hasOwn(geliefert, String(primitiveVon(T, mode, surfaceVon)))
        || (Boolean(saat.brand) && MARKEN_FLAECHEN.includes(surfaceVon))
        || KANDIDATEN_PRIMITIVE(T).some((n) => Object.hasOwn(geliefert, n)));
    const istGeliefert = (pf && Object.hasOwn(geliefert, pf)) || (pb && Object.hasOwn(geliefert, pb)) || Boolean(gelieferteBeschriftung);
    let vorschlag;
    try { vorschlag = aufKontrast(werte(Rk, mode, fg), [werte(Rk, mode, bg)], soll, mode === 'light' ? 'dunkler' : 'heller').hex; } catch { vorschlag = null; }
    befunde.push({ mode, fg, bg, ist, soll, vorschlag, geliefert: istGeliefert });
  }
  const gerechnet = befunde.filter((b) => !b.geliefert);
  if (gerechnet.length) {
    const e = new Error(`gerechnete Werte verfehlen ein Paar: ${gerechnet.map((b) => `${b.mode} ${b.fg}/${b.bg}`).join(', ')}`);
    e.code = 3; throw e;
  }

  return { theme, rollen, befunde, hinweise, ergebnis: Rk, css: css(theme, quelle, rollen, befunde, hinweise) };
}

function block(selector, eintraege) {
  return `${selector} {\n${Object.entries(eintraege).map(([n, v]) => `  --tl-${n}: ${v};`).join('\n')}\n}\n`;
}

function css(theme, quelle, rollen, befunde, hinweise) {
  // Reihenfolge wie in tokens.json: Farbrollen, dann Beschriftungen, dann Effekte (so liegen sie
  // schon in rollen.light), die Maße zuletzt.
  const erster = { ...rollen.light, ...rollen.measure };
  // Ein Pfad, der */ enthaelt, wuerde den Kopfkommentar mittendrin schliessen.
  let out = HERKUNFT(theme, String(quelle).replaceAll('*/', '* /'), befunde.length);
  out += block(`[data-tl-theme="${theme}"]`, erster);
  out += block(`[data-tl-theme="${theme}"][data-tl-mode="dark"]`, rollen.dark);
  if (befunde.length || hinweise.length) {
    out += '\n/* Report\n';
    for (const b of befunde) out += `   finding  ${b.mode}: ${b.fg} on ${b.bg} = ${b.ist.toFixed(2)}, required ${b.soll}${b.vorschlag ? `, suggestion ${b.vorschlag}` : ''}\n`;
    for (const h of hinweise) out += `   note     ${h}\n`;
    out += '*/\n';
  }
  return out;
}

// Aufruf: node tools/derive.mjs <eingabe.json> [<ausgabe.css>] [--strict]
const AUFRUF = 'Aufruf: node tools/derive.mjs <theme>.primitives.json [<ausgabe>.css] [--strict]';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  for (const a of args) if (a.startsWith('--') && a !== '--strict') {
    console.error(`unbekannte Option: ${a}`);
    console.error(AUFRUF);
    process.exit(2);
  }
  const strict = args.includes('--strict');
  const [eingabePfad, ausgabeArg] = args.filter((a) => !a.startsWith('--'));
  if (!eingabePfad) { console.error(AUFRUF); process.exit(2); }
  const hier = dirname(fileURLToPath(import.meta.url));
  const P = JSON.parse(readFileSync(join(hier, '../src/primitives.json'), 'utf8'));
  const T = JSON.parse(readFileSync(join(hier, '../src/tokens.json'), 'utf8'));
  let json;
  try { json = JSON.parse(readFileSync(eingabePfad, 'utf8')); }
  catch (e) { console.error(`${eingabePfad}: ${e.message}`); process.exit(2); }
  let ergebnis;
  try { ergebnis = derive(P, T, json, basename(eingabePfad)); }
  catch (e) {
    if (e instanceof ThemeEingabeFehler) { console.error(`${eingabePfad}: ${e.message}`); process.exit(2); }
    if (e.code === 3) { console.error(`derive-Fehler: ${e.message}`); process.exit(3); }
    throw e;
  }
  for (const b of ergebnis.befunde) console.log(`Befund  ${b.mode}: ${b.fg} auf ${b.bg} = ${b.ist.toFixed(2)}, gefordert ${b.soll}${b.vorschlag ? `, Vorschlag ${b.vorschlag}` : ''}`);
  for (const h of ergebnis.hinweise) console.log(`Hinweis ${h}`);
  if (strict && ergebnis.befunde.length) { console.error(`${ergebnis.befunde.length} Befund(e), --strict: nichts geschrieben`); process.exit(1); }
  const ausgabe = ausgabeArg ?? join(dirname(eingabePfad), `${ergebnis.theme}.theme.css`);
  try { writeFileSync(ausgabe, ergebnis.css); }
  catch (e) { console.error(`${ausgabe}: ${e.message}`); process.exit(2); }
  console.log(`geschrieben: ${ausgabe}`);
}
