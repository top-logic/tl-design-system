// tl-ds derive: ein Kundentheme aus einer Primitivdatei. Rechnet, was fehlt; lässt, was geliefert
// ist; schreibt nur Rollen, die von TopLogic abweichen; meldet, was ein Paar verfehlt.
// Spec: docs/superpowers/specs/2026-09-25-derive-design.md
import { resolve, primitives } from './resolve.mjs';
import { grauRampe, kategorienVerteilen, kategorieRollen, markenRollen, beschriftungAbleiten, hexZuOklch, aufKontrast }
  from './lib/color.mjs';
import { kontrastPaare, werte } from './lib/pairs.mjs';
import { leseThemeEingabe } from './lib/theme-input.mjs';
import { ratio } from './lib/contrast.mjs';

const REF = /^\{([a-z0-9-]+)\}$/;
const MODES = ['light', 'dark'];
const KATEGORIEN = Array.from({ length: 8 }, (_, i) => i + 1);
/**
 * Die drei Flächen, deren Helligkeit unmittelbar aus der Saat des Kunden kommt. Ihre
 * Beschriftungen (text-on-brand, -hover, -active, icon-on-brand) wählen nach der
 * Zwei-Kandidaten-Regel den besseren von Weiß und Fast-Schwarz — nicht den ausreichenden. Eine
 * Saat mittlerer Helligkeit lässt beide Kandidaten unter der Schwelle: das ist keine falsche
 * Rechnung, sondern die Folge einer GELIEFERTEN Farbe, also ein Befund, kein Abbruch. Die Fläche
 * selbst bleibt unangetastet — sie ist die Marke des Kunden.
 */
const MARKEN_FLAECHEN = ['surface-brand', 'surface-brand-hover', 'surface-brand-active'];
const grad = (hex) => ((hexZuOklch(hex).H * 180) / Math.PI + 360) % 360;

const HERKUNFT = (theme, quelle, anzahl) => `/* Generated by TopLogic/tl-design-system, tools/derive.mjs, from ${quelle}.
   Do not edit — edit the JSON and regenerate. Loaded after tokens.css; applies under data-tl-theme="${theme}".
   Findings: ${anzahl} ${anzahl === 1 ? 'pair' : 'pairs'} below its threshold${anzahl ? ' (see report at the end of this file)' : ''}. */\n`;

/** Primitive, die eine Rolle in einem Modus liest — für die Herkunft (geliefert oder gerechnet). */
function primitiveVon(T, mode, rolle) {
  const m = REF.exec(String(T.color[mode][rolle] ?? T.measure[rolle] ?? ''));
  return m ? m[1] : null;
}

export function derive(P, T, json, quelle = 'input') {
  const eingabe = leseThemeEingabe(json, P, T);
  const { theme, geliefert, saat } = eingabe;
  const hinweise = [];

  // 1 Gelieferte Stufen und die Graurampe liegen über den Primitiven.
  const Pk = structuredClone(P);
  if (saat.gray) {
    const grau = Object.fromEntries(Object.entries(P.color).filter(([n]) => n.startsWith('gray-')));
    Object.assign(Pk.color, grauRampe(saat.gray, grau));
  }
  for (const [n, v] of Object.entries(geliefert)) for (const f of Object.keys(Pk)) if (typeof Pk[f] === 'object' && n in Pk[f]) Pk[f][n] = v;

  // 2 Auflösen: geliefertes zieht durch alle Rollen, Beschriftungen folgen den Flächen.
  const R0 = resolve(P, T);
  const Rk = resolve(Pk, T);
  const gruende = Object.fromEntries(MODES.map((m) => [m, [Rk.color[m]['surface-base'], Rk.color[m]['surface-layer']]]));

  // 3 Gerechnete Rollen überlagern, wo keine gelieferte Primitive dahintersteht.
  const setze = (mode, rolle, hex) => {
    const prim = primitiveVon(T, mode, rolle);
    if (prim && prim in geliefert) return;
    Rk.color[mode][rolle] = hex;
  };
  if (saat.brand) {
    const m = markenRollen(saat.brand, gruende);
    hinweise.push(...m.hinweise);
    for (const mode of MODES) for (const [rolle, hex] of Object.entries(m[mode])) setze(mode, rolle, hex);
  }
  const markenTon = grad(Rk.color.light['surface-brand']);
  const bedeutungen = ['error', 'warning', 'success', 'info'].map((s) => grad(Rk.color.light[`status-${s}-surface`]));
  for (const b of bedeutungen) {
    const d = Math.abs(((markenTon - b) % 360 + 540) % 360 - 180);
    if (d < 20) hinweise.push(`die Marke liegt ${d.toFixed(0)}° neben einer Bedeutung; Stufe B entscheidet, ob die Bedeutung einen anderen Ton bekommt`);
  }
  const eigene = saat.category ?? {};
  const fehlende = KATEGORIEN.filter((k) => !(`category-${k}` in eigene));
  const { toene, abstand } = kategorienVerteilen([markenTon, ...bedeutungen, ...Object.values(eigene).map(grad)], fehlende.length);
  if (abstand < 20) hinweise.push(`die Kategorien halten nur ${abstand}° zueinander; der Kreis war mit dieser Marke voller als bei TopLogic`);
  const toneJeKategorie = Object.fromEntries([...KATEGORIEN.map((k) => [k, eigene[`category-${k}`] ? grad(eigene[`category-${k}`]) : null])]);
  fehlende.forEach((k, i) => { toneJeKategorie[k] = toene[i]; });
  for (const k of KATEGORIEN) {
    const r = kategorieRollen(toneJeKategorie[k], gruende);
    for (const mode of MODES) { setze(mode, `category-${k}-subtle`, r[mode].subtle); setze(mode, `category-${k}-border`, r[mode].border); }
  }

  // 4 Beschriftungen für jede Fläche neu, mit den Kandidaten des Kundengraus.
  const prim = primitives(Pk);
  const kandidaten = { dunklerKandidat: prim[REF.exec(T.derived.candidates.dark)[1]], hellerKandidat: prim[REF.exec(T.derived.candidates.light)[1]] };
  for (const mode of MODES) for (const [name, { surface }] of Object.entries(T.derived[mode]))
    Rk.derived[mode][name] = beschriftungAbleiten(Rk.color[mode][surface], kandidaten).hex;

  // 5 Nachführen: derive steht für jeden Wert ein, den es nicht geliefert bekommen hat.
  //
  // Die Graurampe des Kunden ändert die Flächen, nicht aber die Bedeutungsfarben, die TopLogic
  // unverändert lässt. Unsere Palette hat an mehreren Paaren nur Rundungsluft (status-warning-text
  // auf surface-base steht bei 4,50001), also rutscht ein solches Paar bei jeder Temperatur unter
  // seine Schwelle — nicht, weil die Rechnung falsch ist, sondern weil der Grund ein anderer ist.
  // Ein solcher Wert ist nicht geliefert; also führt derive ihn nach, mit derselben Mechanik, die
  // markenRollen und kategorieRollen schon benutzen. Damit gilt die Regel der Spec ohne Ausnahme:
  // ein Befund entsteht nur aus einem GELIEFERTEN Wert.
  const paare = kontrastPaare(T);
  for (const mode of MODES) {
    const jeRolle = new Map();
    for (const { fg, bg, soll } of paare) {
      if (!(fg in Rk.color[mode])) continue; // Beschriftungen folgen ihrer Fläche, nicht dem Kontrast
      const p = primitiveVon(T, mode, fg);
      if (p && p in geliefert) continue; // geliefert: bleibt stehen und wird zum Befund
      if (!jeRolle.has(fg)) jeRolle.set(fg, []);
      jeRolle.get(fg).push({ bg, soll });
    }
    for (const [rolle, liste] of jeRolle) {
      const vorher = Rk.color[mode][rolle];
      let hex = vorher;
      for (const soll of [...new Set(liste.map((x) => x.soll))].sort((a, b) => a - b)) {
        const gegen = liste.filter((x) => x.soll === soll).map((x) => werte(Rk, mode, x.bg));
        try { hex = aufKontrast(hex, gegen, soll, mode === 'light' ? 'dunkler' : 'heller').hex; } catch { /* der Befund meldet es */ }
      }
      if (hex === vorher) continue;
      Rk.color[mode][rolle] = hex;
      hinweise.push(`${mode}: ${rolle} auf dem geänderten Grund nachgeführt (${vorher} → ${hex})`);
    }
  }

  // 6 Differenz: beide Blöcke tragen dieselben Farbrollen.
  const farbRollen = [...Object.keys(T.color.light), ...Object.keys(T.derived.light)].filter((k) => !k.startsWith('_'));
  const effektRollen = Object.keys(T.effect.light).filter((k) => !k.startsWith('_'));
  const abweichend = (r) => MODES.some((m) => werte(Rk, m, r) !== werte(R0, m, r));
  const U = farbRollen.filter(abweichend);
  const E = effektRollen.filter((r) => MODES.some((m) => Rk.effect[m][r] !== R0.effect[m][r]));
  const rollen = { light: {}, dark: {}, measure: {} };
  for (const mode of MODES) {
    for (const r of U) rollen[mode][r] = werte(Rk, mode, r);
    for (const r of E) rollen[mode][r] = Rk.effect[mode][r];
  }
  for (const r of Object.keys(T.measure).filter((k) => !k.startsWith('_'))) if (Rk.measure[r] !== R0.measure[r]) rollen.measure[r] = Rk.measure[r];

  // 7 Befunde: nur gelieferte Werte dürfen ein Paar verfehlen.
  const befunde = [];
  for (const mode of MODES) for (const { fg, bg, soll } of kontrastPaare(T)) {
    const ist = ratio(werte(Rk, mode, fg), werte(Rk, mode, bg));
    if (ist >= soll) continue;
    const pf = primitiveVon(T, mode, fg), pb = primitiveVon(T, mode, bg);
    const surfaceVon = T.derived[mode][fg]?.surface;
    const gelieferteBeschriftung = surfaceVon
      && (primitiveVon(T, mode, surfaceVon) in geliefert
        || (Boolean(saat.brand) && MARKEN_FLAECHEN.includes(surfaceVon)));
    const istGeliefert = (pf && pf in geliefert) || (pb && pb in geliefert) || Boolean(gelieferteBeschriftung);
    let vorschlag;
    try { vorschlag = aufKontrast(werte(Rk, mode, fg), [werte(Rk, mode, bg)], soll, mode === 'light' ? 'dunkler' : 'heller').hex; } catch { vorschlag = null; }
    befunde.push({ mode, fg, bg, ist, soll, vorschlag, geliefert: istGeliefert });
  }
  const gerechnet = befunde.filter((b) => !b.geliefert);
  if (gerechnet.length) {
    const e = new Error(`gerechnete Werte verfehlen ein Paar: ${gerechnet.map((b) => `${b.mode} ${b.fg}/${b.bg}`).join(', ')}`);
    e.code = 3; throw e;
  }

  return { theme, rollen, befunde, hinweise, ergebnis: Rk, css: css(theme, quelle, rollen, befunde, hinweise) };
}

function block(selector, eintraege) {
  return `${selector} {\n${Object.entries(eintraege).map(([n, v]) => `  --tl-${n}: ${v};`).join('\n')}\n}\n`;
}

function css(theme, quelle, rollen, befunde, hinweise) {
  const erster = { ...rollen.measure, ...rollen.light };
  let out = HERKUNFT(theme, quelle, befunde.length);
  out += block(`[data-tl-theme="${theme}"]`, erster);
  out += block(`[data-tl-theme="${theme}"][data-tl-mode="dark"]`, rollen.dark);
  if (befunde.length || hinweise.length) {
    out += '\n/* Report\n';
    for (const b of befunde) out += `   finding  ${b.mode}: ${b.fg} on ${b.bg} = ${b.ist.toFixed(2)}, required ${b.soll}${b.vorschlag ? `, suggestion ${b.vorschlag}` : ''}\n`;
    for (const h of hinweise) out += `   note     ${h}\n`;
    out += '*/\n';
  }
  return out;
}
